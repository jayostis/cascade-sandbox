import { writeFile } from "node:fs/promises";
import { brandsBundle } from "../brands.js";
import { loadHospitals } from "./index.js";

/** Writes `DEMO_BRANDS`, the demo hospitals' brands bundle, as a TypeScript module at the path given. */
async function main(output: string | undefined): Promise<void> {
  if (output === undefined) throw new Error("usage: brands-cli <output.ts>");
  const bundle = brandsBundle(
    (await loadHospitals()).map(({ hospital }) => hospital),
    new Date().toISOString(),
  );
  await writeFile(
    output,
    `/** Generated by \`npm run brands\` from the demo hospitals' folders: do not edit. */\nexport const DEMO_BRANDS = ${JSON.stringify(bundle, null, 2)};\n`,
  );
}

main(process.argv[2]).catch((error: unknown) => {
  console.error(error instanceof Error ? error.message : error);
  process.exitCode = 1;
});
