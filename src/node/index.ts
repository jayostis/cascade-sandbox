const folderOf = (path: string) =>
  fileURLToPath(new URL(`../../../${path}/`, import.meta.url));

/** The package's own hospitals: a folder of hospital folders, each holding its `hospital.json`. */
export const HOSPITALS_FOLDER = folderOf("hospitals");
/** The package's own people, generated by Synthea: a folder of person folders. */
export const PEOPLE_FOLDER = folderOf("people");
/** The vocabulary's hand-written people, copied at the commit `vocabulary.json` pins. */
export const VOCABULARY_PEOPLE = folderOf("vocabulary/people");
export const DEFAULT_ROOTS = {
  hospitals: [HOSPITALS_FOLDER],
  people: [PEOPLE_FOLDER, VOCABULARY_PEOPLE],
} as const;

/** The folders hospitals and people are loaded from; each list absent is its `DEFAULT_ROOTS` list. */
export interface Roots {
  hospitals?: readonly string[];
  people?: readonly string[];
}

export type LoadedHospital = {
  hospital: Hospital;
  patients: Record<string, Bundle>;
};

function checkHospital(value: unknown, where: string): Hospital {
  const refuse = (reason: string) => new HospitalDataError(where, reason);
  if (!isObject(value)) throw refuse("is not an object");
  for (const field of ["name", "fhirBase"])
    if (typeof value[field] !== "string")
      throw refuse(`has no ${field}, a string`);
  if (value.colour !== undefined && typeof value.colour !== "string")
    throw refuse("has a colour that is not a string");
  if (value.places !== undefined && !isStrings(value.places))
    throw refuse("has places that are not a list of strings");
  if (
    typeof value.pageSize !== "number" ||
    !Number.isInteger(value.pageSize) ||
    value.pageSize < 1
  )
    throw refuse("has no pageSize, a whole number of 1 or more");
  if (typeof value.key !== "string" || value.key === "")
    throw refuse("has no key, a string");
  if (!isStrings(value.types)) throw refuse("has no types, a list of strings");
  if (!isStrings(value.hiddenFromSearch))
    throw refuse("has no hiddenFromSearch, a list of strings");
  return value as unknown as Hospital;
}

function idOf(hospital: Hospital, where: string): string {
  try {
    return hospitalId({ hospital, patients: {} });
  } catch (error) {
    throw new HospitalDataError(
      where,
      error instanceof Error ? error.message : String(error),
    );
  }
}

/** Each hospital folder of the roots, by id: roots in order, then each root's folders by name. */
async function hospitalsIn(
  roots: readonly string[],
): Promise<Map<string, Hospital>> {
  const hospitals = new Map<string, Hospital>();
  for (const root of roots) {
    if ((await kind(root)) !== "folder") continue;
    for (const name of (await readdir(root)).sort()) {
      if (name.startsWith(".")) continue;
      const folder = join(root, name);
      if ((await kind(folder)) !== "folder") continue;
      const where = `${name}/hospital.json`;
      const file = join(folder, "hospital.json");
      if ((await kind(file)) !== "file")
        throw new HospitalDataError(where, "is not there");
      const hospital = checkHospital(await readJson(file, where), where);
      const id = idOf(hospital, where);
      if (name !== id)
        throw new HospitalDataError(
          where,
          `has the folder name ${name}, but its fhirBase names ${id}`,
        );
      if ((await kind(join(folder, "patients"))) !== undefined)
        throw new HospitalDataError(
          name,
          `holds patients/: a hospital is its settings, and its patients are people/<person>/sources/${id}/fhir.json`,
        );
      if (hospitals.has(id))
        throw new HospitalDataError("hospital.json", `two hospitals at ${id}`);
      hospitals.set(id, hospital);
    }
  }
  return hospitals;
}

/**
 * Every hospital in the roots given (the package's own by default), as `demoFetch` takes them, in root order and then
 * by folder name. A hospital's patients are every loaded person with a source of its id, keyed by the Patient id there.
 * A root that is not a folder is skipped, and so is a file where a hospital folder would be, and a name with a leading
 * dot (`.git`). Two hospitals with one id throw, and so does a person's source at no hospital.
 */
export async function loadHospitals(
  roots: Roots = {},
): Promise<LoadedHospital[]> {
  return assemble(
    await hospitalsIn(roots.hospitals ?? DEFAULT_ROOTS.hospitals),
    await loadPeople(roots.people ?? DEFAULT_ROOTS.people),
  );
}

/** The hospitals with their patients, every person's sources placed and each hospital's patient files checked. */
function assemble(
  hospitals: ReadonlyMap<string, Hospital>,
  people: readonly LoadedPerson[],
): LoadedHospital[] {
  const placed = new Map(
    [...hospitals.keys()].map((id) => [
      id,
      {
        patients: {} as Record<string, Bundle>,
        places: {} as Record<string, string>,
        holders: {} as Record<string, string>,
      },
    ]),
  );
  for (const { person, sources } of people)
    for (const [source, bundle] of Object.entries(sources)) {
      const at = placed.get(source);
      if (at === undefined)
        throw new HospitalDataError(
          `${person.id}/sources/${source}`,
          `there is no hospital ${source}`,
        );
      const where = `${person.id}/sources/${source}/fhir.json`;
      const id = patientOf(bundle, where);
      const other = at.holders[id];
      if (other !== undefined)
        throw new HospitalDataError(
          where,
          `holds Patient ${id}, which ${other} holds at ${source} too`,
        );
      at.patients[id] = bundle;
      at.places[id] = where;
      at.holders[id] = person.id;
    }
  return [...hospitals].map(([id, hospital]) => {
    const { patients, places } = placed.get(id)!;
    patientRecords(hospital.fhirBase, patients, places);
    return { hospital, patients };
  });
}

/** The hospital of the id given, from the roots given. */
export async function loadHospital(
  id: string,
  roots: Roots = {},
): Promise<LoadedHospital> {
  const found = (await loadHospitals(roots)).find(
    ({ hospital }) => hospitalId({ hospital, patients: {} }) === id,
  );
  if (found === undefined)
    throw new HospitalDataError("hospital.json", `there is no hospital ${id}`);
  return found;
}

/**
 * Each story's written answer, `expected/story.json`, of the people in the roots given, in the order of their ids: its
 * patient is the Patient of the story's hospital there, and `ccdaFile` the absolute path of its C-CDA copy.
 */
export async function loadStories(
  roots: readonly string[] = DEFAULT_ROOTS.people,
): Promise<Story[]> {
  const stories: Story[] = [];
  for (const { folder, person, sources } of await loadPeople(roots)) {
    const file = join(folder, "expected", "story.json");
    if ((await kind(file)) !== "file") continue;
    const where = `${person.id}/expected/story.json`;
    const { ccda, ...story } = (await readJson(file, where)) as Omit<
      Story,
      "patient" | "ccdaFile"
    > & { ccda?: string };
    const source = sources[story.hospital];
    if (source === undefined)
      throw new HospitalDataError(
        where,
        `names the hospital ${String(story.hospital)}, where ${person.id} has no source`,
      );
    const ccdaFile =
      ccda === undefined ? undefined : join(folder, ...ccda.split("/"));
    if (ccdaFile !== undefined && (await kind(ccdaFile)) !== "file")
      throw new HospitalDataError(where, `names ${ccda}, which is not there`);
    stories.push({
      ...story,
      patient: patientOf(
        source,
        `${person.id}/sources/${story.hospital}/fhir.json`,
      ),
      ...(ccdaFile === undefined ? {} : { ccdaFile }),
    });
  }
  return stories;
}

/** A Person from a Patient, or a refusal naming the field it lacks. */
function personFrom(patient: Resource, where: string): Person {
  const id = patient.id as string;
  const name = officialName(patient);
  const lacks = (field: string) =>
    new HospitalDataError(
      where,
      `holds Patient ${id} with no ${field}, which its person.json needs`,
    );
  if (!isName(name)) throw lacks("name of family and given names");
  if (typeof patient.birthDate !== "string") throw lacks("birthDate");
  if (
    !["male", "female", "other", "unknown"].includes(patient.gender as string)
  )
    throw lacks("gender");
  return {
    id,
    name,
    birthDate: patient.birthDate,
    gender: patient.gender as Person["gender"],
  };
}

/**
 * Checks a patient's file as the app at `app` would load it at `hospital`, one of the package's hospitals or the app's
 * own `hospitals/`, and writes it as `people/<Patient id>/sources/<hospital>/fhir.json` in the app, with the person's
 * `person.json` from the Patient's official name, birth date and gender when the folder has none. The file is a plain
 * or history Bundle, written as it is, or an authoring file with `shorthand`, compiled first. Refuses a patient who is
 * already at that hospital. Gives the path written.
 */
export async function addPatient(
  app: string,
  hospital: string,
  file: string,
): Promise<string> {
  const where = basename(file);
  let text: string;
  try {
    text = await readFile(resolve(file), "utf8");
  } catch (error) {
    throw new HospitalDataError(
      where,
      `cannot be read: ${(error as Error).message}`,
    );
  }
  let parsed: unknown;
  try {
    parsed = JSON.parse(text);
  } catch {
    throw new HospitalDataError(where, "is not JSON");
  }
  let bundle = checkBundle(parsed, where);
  if (bundle.resourceType !== "Bundle")
    throw new HospitalDataError(where, "is not a Bundle");
  if (hasShorthand(bundle))
    bundle = compileShorthand(bundle as ShorthandBundle, where);
  const id = patientOf(bundle, where);
  if (!/^[a-z0-9]+(-[a-z0-9]+)*$/.test(id))
    throw new HospitalDataError(
      where,
      `holds Patient ${id}, which is not a person's folder name: lower-case letters and digits joined by -`,
    );
  const root = resolve(app);
  const people = join(root, "people");
  const hospitals = await hospitalsIn([
    ...DEFAULT_ROOTS.hospitals,
    join(root, "hospitals"),
  ]);
  const at = hospitals.get(hospital);
  if (at === undefined)
    throw new HospitalDataError(
      "hospital.json",
      `there is no hospital ${hospital}`,
    );
  const loaded = await loadPeople([...DEFAULT_ROOTS.people, people]);
  const folder = join(people, id);
  const known = loaded.find((one) => one.person.id === id);
  if (known !== undefined && known.folder !== folder)
    throw new HospitalDataError(
      where,
      `holds Patient ${id}, which is a person of ${dirname(known.folder)} already: give the patient another id`,
    );
  const name = `${id}/sources/${hospital}/fhir.json`;
  if (known !== undefined && hospital in known.sources)
    throw new HospitalDataError(
      name,
      "is already at this hospital: remove it first, or give the patient another id",
    );
  const person =
    known?.person ??
    personFrom(
      recordsAt(bundle).find(({ resourceType }) => resourceType === "Patient")!,
      where,
    );
  const staged: LoadedPerson = {
    folder,
    person,
    sources: { ...known?.sources, [hospital]: bundle },
    documents: known?.documents ?? [],
  };
  checkIdentity(staged.person, staged.sources, staged.documents);
  assemble(hospitals, [...loaded.filter((one) => one !== known), staged]);
  for (const record of versionsOf(bundle, name).keys()) {
    const type = record.slice(0, record.indexOf("/"));
    if (!at.types.includes(type))
      throw new HospitalDataError(
        name,
        `${record} is ${/^[AEIOU]/.test(type) ? "an" : "a"} ${type}, which hospital.json does not list in types`,
      );
  }
  const path = join(folder, "sources", hospital, "fhir.json");
  await mkdir(join(folder, "sources", hospital), { recursive: true });
  await writeFile(path, `${JSON.stringify(bundle, null, 2)}\n`, { flag: "wx" });
  if (known === undefined)
    await writeFile(
      join(folder, "person.json"),
      `${JSON.stringify(person, null, 2)}\n`,
      { flag: "wx" },
    );
  return path;
}

