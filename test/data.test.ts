import assert from "node:assert/strict";
import { stat } from "node:fs/promises";
import { before, describe, it } from "node:test";
import { type Resource, recordsAt } from "../src/index.js";
import {
  DEFAULT_ROOTS,
  loadHospitals,
  loadPeople,
  loadStories,
} from "../src/node/index.js";

const ICD = "http://hl7.org/fhir/sid/icd-10-cm";
const CVX = "http://hl7.org/fhir/sid/cvx";
const LOINC = "http://loinc.org";
const RXNORM = "http://www.nlm.nih.gov/research/umls/rxnorm";

type Hospital = Awaited<ReturnType<typeof loadHospitals>>[number];

const idOf = ({ hospital }: Hospital) =>
  new URL(hospital.fhirBase).hostname.split(".")[0];

function codings(value: unknown): string[] {
  if (Array.isArray(value)) return value.flatMap(codings);
  if (!value || typeof value !== "object") return [];
  const object = value as Record<string, unknown>;
  const own =
    typeof object.system === "string" && typeof object.code === "string"
      ? [`${object.system}|${object.code}`]
      : [];
  return [...own, ...Object.values(object).flatMap(codings)];
}

/** The record of the type that the patient holds under the code of the system; the leaf that asks needs it there. */
function has(
  hospital: Hospital,
  patient: string,
  type: string,
  system: string,
  code: string,
): Resource {
  const found = recordsAt(
    hospital.patients[patient] ?? {
      resourceType: "Bundle",
      type: "collection",
    },
  ).find(
    (record) =>
      record.resourceType === type &&
      codings(record.code ?? record.vaccineCode ?? record).includes(
        `${system}|${code}`,
      ),
  );
  assert.ok(found, `${patient} holds no ${type} under ${system}|${code}`);
  return found;
}

const displayOf = (record: Resource) =>
  String(
    (
      (record.medicationCodeableConcept ?? record.code) as
        { coding: { display?: string }[] } | undefined
    )?.coding[0]?.display,
  );

const recordedBefore = (earlier: Resource, later: Resource, field: string) =>
  Date.parse(String(earlier[field])) < Date.parse(String(later[field]));

/**
 * The package carries two demo hospitals, Cascade North and Cascade South, and the made-up people who are patients
 * there: hand-written ones, five stories, and three generated by Synthea. A test signs in as one of them by the
 * patient id listed here.
 */
describe("People to sign in as · loadHospitals(), loadPeople(), loadStories()", () => {
  let north: Hospital;
  let south: Hospital;
  let hospitals: Hospital[];
  let stories: Awaited<ReturnType<typeof loadStories>>;
  let people: Awaited<ReturnType<typeof loadPeople>>;

  before(async () => {
    hospitals = await loadHospitals();
    north = hospitals.find((one) => idOf(one) === "cascade-north")!;
    south = hospitals.find((one) => idOf(one) === "cascade-south")!;
    stories = await loadStories();
    people = await loadPeople(DEFAULT_ROOTS.people);
  });

  describe("loadHospitals()", () => {
    const patientsAt = (id: string) =>
      Object.keys(
        hospitals.find((one) => idOf(one) === id)?.patients ?? {},
      ).sort();

    it("returns Cascade North with its nine patients", () => {
      assert.deepEqual(patientsAt("cascade-north"), [
        "pt-1001",
        "pt-1002",
        "story-red-herring",
        "story-side-effect",
        "story-statin",
        "story-stopped",
        "story-too-little",
        "syn-c521b4f4b8f5b303",
        "syn-eb3d267fcb803202",
      ]);
    });

    it("returns Cascade South with its three patients", () => {
      assert.deepEqual(patientsAt("cascade-south"), [
        "s-48213",
        "syn-0c7c8edf48f450e1",
        "syn-25b2cdfcaf0b380e",
      ]);
    });
  });

  describe("given Rowan Ellery Marsh", () => {
    const rowan = () => {
      const found = people.find(
        ({ person }) => person.id === "rowan-ellery-marsh",
      );
      assert.ok(found);
      return found;
    };

    it("holds a source at each hospital", () => {
      assert.deepEqual(Object.keys(rowan().sources), [
        "cascade-north",
        "cascade-south",
      ]);
    });

    it("serves the person under each hospital's own patient id", () => {
      assert.ok("pt-1001" in north.patients);
      assert.ok("s-48213" in south.patients);
    });

    it("serves at a hospital the file that is the person's source there", () => {
      assert.deepEqual(
        north.patients["pt-1001"],
        rowan().sources["cascade-north"],
      );
    });
  });

  describe("loadStories()", () => {
    it("returns five stories, each naming a patient Cascade North holds", () => {
      assert.equal(stories.length, 5);
      assert.deepEqual(
        stories.map(({ hospital }) => hospital),
        Array(5).fill("cascade-north"),
      );
      assert.deepEqual(stories.map(({ patient }) => patient).sort(), [
        "story-red-herring",
        "story-side-effect",
        "story-statin",
        "story-stopped",
        "story-too-little",
      ]);
      for (const { patient } of stories) assert.ok(patient in north.patients);
    });

    it("gives one story the path of a C-CDA document that is there", async () => {
      const documents = stories.flatMap(({ ccdaFile }) => ccdaFile ?? []);
      assert.equal(documents.length, 1);
      assert.ok(
        documents[0]!.replaceAll("\\", "/").endsWith("ccda/2025-02-01.xml"),
      );
      assert.ok((await stat(documents[0]!)).isFile());
    });
  });

  describe("given the codes the reference tables join", () => {
    it("holds a retired ICD-10-CM code and its replacement, the retired one recorded first", () => {
      const [retired, replacement] = ["T84.040A", "M97.01XA"].map((code) =>
        has(north, "pt-1002", "Condition", ICD, code),
      );
      for (const condition of [retired!, replacement!])
        assert.deepEqual(
          codings(condition.code).filter(
            (coding) => !coding.startsWith(`${ICD}|`),
          ),
          [],
          "coded by ICD-10-CM alone, so only the conversion joins them",
        );
      assert.ok(recordedBefore(retired!, replacement!, "recordedDate"));
    });

    it("holds an immunization under CVX 154", () => {
      has(north, "pt-1002", "Immunization", CVX, "154");
    });

    it("holds two HDL results under two LOINC codes, 2086-7 before 2085-9", () => {
      const [first, second] = ["2086-7", "2085-9"].map((code) =>
        has(north, "pt-1002", "Observation", LOINC, code),
      );
      assert.ok(recordedBefore(first!, second!, "effectiveDateTime"));
    });

    it("holds a brand at North and its generic at South", () => {
      const brand = has(
        north,
        "pt-1001",
        "MedicationRequest",
        RXNORM,
        "206805",
      );
      const generic = has(
        south,
        "s-48213",
        "MedicationRequest",
        RXNORM,
        "311372",
      );
      assert.match(displayOf(brand), /Claritin/);
      assert.match(displayOf(generic), /loratadine/);
    });

    it("holds an allergy at each hospital, under RxNorm 723 and 308191", () => {
      has(north, "pt-1001", "AllergyIntolerance", RXNORM, "723");
      has(south, "s-48213", "AllergyIntolerance", RXNORM, "308191");
    });

    it("holds one medicine at two strengths, the 10 mg order before the 20 mg", () => {
      const ten = has(south, "s-48213", "MedicationRequest", RXNORM, "314076");
      const twenty = has(
        south,
        "s-48213",
        "MedicationRequest",
        RXNORM,
        "314077",
      );
      has(north, "pt-1001", "MedicationRequest", RXNORM, "314076");
      assert.match(displayOf(ten), /lisinopril 10 MG/);
      assert.match(displayOf(twenty), /lisinopril 20 MG/);
      assert.ok(recordedBefore(ten, twenty, "authoredOn"));
    });

    it("holds the brand, the generic and the 20 mg order as active", () => {
      for (const [hospital, patient, code] of [
        [north, "pt-1001", "206805"],
        [south, "s-48213", "311372"],
        [south, "s-48213", "314077"],
      ] as const)
        assert.equal(
          has(hospital, patient, "MedicationRequest", RXNORM, code).status,
          "active",
          code,
        );
    });
  });
});
